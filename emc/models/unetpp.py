class UNetPlusPlus(nn.Module):
    """Thin adapter around the official NestedUNet (see module docstring).

    forward (deep_supervision=True):  ((aux1, aux2, aux3), out)   — all sigmoid
    forward (deep_supervision=False): out                         — sigmoid
    """

    def __init__(self, num_classes=1, input_channels=3, deep_supervision=True):
        super().__init__()
        self.deep_supervision = deep_supervision
        self.net = NestedUNet(num_classes=num_classes,
                              input_channels=input_channels,
                              deep_supervision=deep_supervision)
        self.apply(self._init_weights)

    def _init_weights(self, m):
        # Same Conv/Linear init style as EGE-UNet, so neither baseline gets an
        # accidental initialisation advantage. BatchNorm keeps PyTorch defaults.
        if isinstance(m, nn.Conv2d):
            fan_out = m.kernel_size[0] * m.kernel_size[1] * m.out_channels
            fan_out //= m.groups
            m.weight.data.normal_(0, math.sqrt(2.0 / fan_out))
            if m.bias is not None:
                m.bias.data.zero_()
        elif isinstance(m, nn.Linear):
            nn.init.trunc_normal_(m.weight, std=.02)
            if m.bias is not None:
                nn.init.constant_(m.bias, 0)

    def forward(self, x):
        y = self.net(x)
        if self.deep_supervision:
            o1, o2, o3, o4 = y          # NestedUNet returns [o1, o2, o3, o4]
            aux = (torch.sigmoid(o1), torch.sigmoid(o2), torch.sigmoid(o3))
            return aux, torch.sigmoid(o4)
        else:
            return torch.sigmoid(y)
