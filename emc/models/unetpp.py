"""UNet++ (Zhou et al., IEEE TMI 2020).

``VGGBlock`` and ``NestedUNet`` are copied verbatim from the widely used PyTorch
implementation https://github.com/4uiiurz1/pytorch-nested-unet (archs.py), with
nb_filter = [32, 64, 128, 256, 512].

``UNetPlusPlus`` is a thin wrapper: it applies a sigmoid to every output and, with
deep supervision, returns ((X01, X02, X03), X04), where X04 is the prediction.
"""
import math
import torch
from torch import nn

__all__ = ['VGGBlock', 'NestedUNet', 'UNetPlusPlus']


